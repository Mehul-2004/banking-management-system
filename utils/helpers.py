
def print_separator():
    print("\n" + "=" * 40)


def print_title(title):
    print("\n" + "=" *40 )
    print(title)
    print("=" * 40)

def print_success(message):
    print("\n" + "-" * 40)
    print(f"Success: {message}")
    print("-" * 40)
    
def print_error(message):
    print("\n" + "-" * 40)
    print(f"Error: {message}")
    print("-" * 40)

